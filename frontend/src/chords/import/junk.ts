/**
 * Типовой мусор, который копируется вместе с песней с сайтов аккордов. Строка удаляется при
 * импорте, если подходит под любой шаблон. Шаблоны проверяются по всей строке (без пробелов по
 * краям, регистр не важен) — чтобы «аккорды» в заголовке «Исполнитель — Песня (аккорды)» не
 * удалили сам заголовок. Новые шаблоны добавлять сюда.
 */
export const JUNK_PATTERNS: RegExp[] = [
  // «Аккорды», «Аккорды для гитары», «Подбор аккордов», «Chords», «Tabs»
  /^(подбор )?аккорд(ы|ов)( и текст( песни)?| для гитары| к песне| песни| на гитаре)?[.:!]?$/i,
  /^(текст( песни)? и аккорды|(guitar )?chords( and lyrics)?|tabs?|guitar tabs?)$/i,
  /^(показать|скрыть|спрятать|убрать) (аппликатуры|аккорды|схемы|схемы аккордов|диаграммы)$/i,
  /^(аппликатуры|схемы)( аккордов)?$/i,
  /^(авто ?скролл|автопрокрутка|прокрутка|скорость( прокрутки)?|auto ?scroll|scroll speed)$/i,
  /^(распечатать|печать|версия для печати|print)$/i,
  /^(транспонировать|транспонирование|transpose)$/i,
  /^(размер шрифта|шрифт|font size)$/i,
  /^(скачать|поделиться|(добавить )?в избранное|сохранить|комментарии|оценить|рейтинг|(смотреть )?видео(разбор)?|разбор|слушать)$/i,
  /^(источник|source)\s*:.*$/i,
  /^просмотр(ов|ы)?\s*:?\s*\d[\d\s]*$/i,
  /^\d[\d\s]*просмотр(ов|а)?$/i,
  /^(©|\(c\)).*$/i,
  /^все права защищены.*$/i,
  // URL в любом месте строки
  /^.*(https?:\/\/|www\.)\S+.*$/i,
]

export function isJunkLine(line: string): boolean {
  const trimmed = line.trim()
  return trimmed !== '' && JUNK_PATTERNS.some((pattern) => pattern.test(trimmed))
}
